// Release map (clean-up round 2): which pages, copy files and components each release needs, so nobody deletes a V1.1 or V1.2
// component because the V1.0 build does not use it. Follows relative imports from each release's page files.
// Usage: node scripts/release-map.mjs            prints the map
//        node scripts/release-map.mjs --write    writes docs/architecture/release-map.md
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve('src');
// Release plan (docs/plan/site-map-plan.md). Edit here when a page moves between releases.
const RELEASES = [
  { name: 'V1.0 (live)', pages: ['index.astro', 'book.astro', 'book/confirmed.astro', 'privacy.astro', 'terms.astro', '404.astro', 'llms.txt.ts', 'robots.txt.ts', 'og/[...slug].png.ts'] },
  { name: 'V1.1 (services, proof, method)', pages: ['validate.astro', 'build.astro', 'scale.astro', 'work/index.astro', 'work/edtech-ai-agents.astro', 'how-we-work.astro', 'about.astro'] },
  { name: 'V1.2 (Review, partners, tools, insights)', pages: ['launch-ready.astro', 'partners.astro', 'launch-check.astro', 'insights/index.astro', 'insights/[slug].astro', 'insights/rss.xml.ts'] },
  { name: 'Private (not shipped)', pages: ['design-system.astro'] },
];

const files = new Map();
(function walk(dir) {
  for (const name of fs.readdirSync(dir)) {
    if (name === 'node_modules' || name === '.astro') continue;
    const f = path.join(dir, name);
    if (fs.statSync(f).isDirectory()) walk(f);
    else if (/\.(astro|ts|js|css|json|md|mdx)$/.test(name)) files.set(f.split(path.sep).join('/'), fs.readFileSync(f, 'utf8'));
  }
})(ROOT);

const rel = (p) => 'src/' + path.relative(ROOT, p).split(path.sep).join('/');
const abs = (p) => path.join(ROOT, p).split(path.sep).join('/');
const resolve = (from, spec) => {
  const base = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
  for (const c of [base, `${base}.ts`, `${base}.astro`, `${base}.js`, `${base}.json`, `${base}/index.ts`, `${base}/index.astro`]) if (files.has(c)) return c;
  return null;
};
const imports = (p) => [...files.get(p).matchAll(/(?:from|import)\s*\(?\s*['"](\.{1,2}\/[^'"]+)['"]/g)].map((m) => resolve(p, m[1])).filter(Boolean);
const reach = (start) => {
  const seen = new Set(start);
  const stack = [...start];
  while (stack.length) for (const d of imports(stack.pop())) if (!seen.has(d)) { seen.add(d); stack.push(d); }
  return seen;
};

const claimed = new Set();
const lines = ['# Release map', '', 'Generated by `node scripts/release-map.mjs --write` from the page lists in that script and the real imports. A file is listed under the first release that needs it. **Do not delete a file from a later release because the live build does not use it.**', ''];
for (const r of RELEASES) {
  const start = r.pages.map((p) => abs('pages/' + p)).filter((p) => files.has(p));
  const all = [...reach(start)].filter((p) => !claimed.has(p));
  all.forEach((p) => claimed.add(p));
  const group = (re) => all.map(rel).filter((p) => re.test(p)).sort();
  lines.push(`## ${r.name}`, '');
  lines.push(`- Pages (${start.length}): ${start.map((p) => '`' + rel(p).replace('src/pages/', '') + '`').join(', ')}`);
  const copy = group(/^src\/content\/copy\//);
  const comps = group(/^src\/components\//);
  const rest = all.map(rel).filter((p) => !/^src\/(pages|content\/copy|components)\//.test(p)).sort();
  lines.push(`- Copy (${copy.length}): ${copy.map((p) => '`' + p.split('/').pop() + '`').join(', ') || 'none new'}`);
  lines.push(`- Components (${comps.length}): ${comps.map((p) => '`' + p.replace('src/components/', '') + '`').join(', ') || 'none new'}`);
  lines.push(`- Other (${rest.length}): ${rest.map((p) => '`' + p.replace('src/', '') + '`').join(', ') || 'none new'}`, '');
}
const orphans = [...files.keys()].filter((p) => /\/components\/.*\.astro$/.test(p) && !claimed.has(p)).map(rel);
lines.push('## Not reached by any page', '', orphans.length ? orphans.map((p) => `- \`${p}\``).join('\n') + '\n\nThese are planned for later (for example the home Guides band returns in V1.2) or are dead code: check `knip` and `docs/architecture/cleanup-plan-v2.md` before deleting.' : 'None.', '');
const out = lines.join('\n');
if (process.argv.includes('--write')) { fs.mkdirSync('docs/architecture', { recursive: true }); fs.writeFileSync('docs/architecture/release-map.md', out); console.log('wrote docs/architecture/release-map.md'); }
else console.log(out);
